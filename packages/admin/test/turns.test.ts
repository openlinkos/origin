import type { EventRow } from '@openlinkos/origin-core';
import { describe, expect, it } from 'vitest';
import {
  dayIndex,
  dayKey,
  groupTurns,
  noteOf,
  resultStatus,
  type TurnItem,
  toolArgument,
} from '../src/turns.js';

let clock = Date.UTC(2026, 9, 20, 9);
let n = 0;
/** An event of a synthetic session, a second after the one before. */
function ev(o: Partial<EventRow> & Pick<EventRow, 'role' | 'kind' | 'text'>): EventRow {
  clock += 1000;
  n++;
  return {
    id: o.id ?? `fake:e${n}`,
    source: 'fake',
    sessionId: 's',
    parentId: null,
    ts: o.ts ?? clock,
    project: 'demo',
    cwd: o.cwd ?? '/home/dev/demo',
    gitBranch: null,
    rawFileId: 1,
    rawLine: n,
    agentVersion: null,
    meta: null,
    ...o,
  };
}
const user = (text: string, o: Partial<EventRow> = {}) =>
  ev({ role: 'user', kind: 'message', text, ...o });
const reply = (text: string, o: Partial<EventRow> = {}) =>
  ev({ role: 'assistant', kind: 'message', text, ...o });
const call = (name: string, input: string, meta: Record<string, unknown> = {}) =>
  ev({
    role: 'assistant',
    kind: 'tool_use',
    text: `${name} ${input}`,
    meta: { toolName: name, ...meta },
  });
const result = (text: string, meta: Record<string, unknown> | null = null) =>
  ev({ role: 'user', kind: 'tool_result', text, meta });

const kinds = (items: TurnItem[]) => items.map((i) => i.type);

describe('turns', () => {
  it('start at each prompt, with what came before the first as turn 0', () => {
    const caveat = ev({
      role: 'user',
      kind: 'meta',
      text: '<local-command-caveat>Caveat: generated by local commands.</local-command-caveat>',
    });
    const command = user('<command-name>/model</command-name>\n<command-args>opus</command-args>');
    const output = user(
      '<local-command-stdout>Set model to \u001b[1mopus\u001b[22m</local-command-stdout>',
    );
    const p1 = user('Fix the login test.');
    const r1 = reply('Fixed.');
    const p2 = user('Now the docs.');
    const interrupted = user('[Request interrupted by user]');
    const turns = groupTurns(
      [caveat, command, output, p1, r1, p2, interrupted],
      [{ id: p1.id }, { id: p2.id }],
      1,
    );
    expect(turns.map((t) => [t.number, t.prompt?.id ?? null, t.events])).toEqual([
      [0, null, 3],
      [1, p1.id, 2],
      [2, p2.id, 2],
    ]);
    // Command echoes, their output, and injected context are notes, not prompts.
    expect(
      turns[0]?.lead.map((i) => (i.type === 'note' ? [i.note.kind, i.note.label] : null)),
    ).toEqual([
      ['context', 'local-command-caveat: Caveat: generated by local commands.'],
      ['command', '/model opus'],
      ['output', 'Set model to opus'],
    ]);
    expect(turns[1]?.reply?.id).toBe(r1.id);
    expect(turns[2]?.reply).toBeNull();
    expect(turns[2]?.lead.map((i) => (i.type === 'note' ? i.note : null))).toEqual([
      { kind: 'notice', label: '[Request interrupted by user]', detail: null },
    ]);
  });

  it('number the turns of a later page from its first prompt', () => {
    const p = user('Go on.');
    const turns = groupTurns([p, reply('Done.')], [{ id: p.id }], 21);
    expect(turns.map((t) => t.number)).toEqual([21]);
    // A turn shown in parts: its later parts have no prompt.
    expect(groupTurns([reply('More.')], [], 22).map((t) => [t.number, t.prompt])).toEqual([
      [21, null],
    ]);
  });

  it('pair calls with results by call id, or else the first open call without one', () => {
    const p = user('Look around.');
    const a = call('Read', '{"file_path":"/home/dev/demo/src/a.ts"}', { toolUseId: 'toolu_a' });
    const b = call('Bash', '{"command":"git status"}', { toolUseId: 'toolu_b' });
    const rb = result('clean', { toolUseId: 'toolu_b' });
    const ra = result('Error: no such file', { toolUseId: 'toolu_a', isError: true });
    const c = call('shell', 'ls -la');
    const d = call('shell', 'pwd');
    const rc = result('a b c');
    const rd = result('/home', { status: 'failed' });
    const e = call('Grep', '{"pattern":"TODO"}', { callId: 'call_e' });
    const orphan = result('late', { callId: 'call_gone' });
    const last = reply('All done.');
    const [turn] = groupTurns([p, a, b, rb, ra, c, d, rc, rd, e, orphan, last], [{ id: p.id }], 1);
    const tools = (turn?.work ?? []).flatMap((i) => (i.type === 'tool' ? [i.tool] : []));
    expect(
      tools.map((t) => [t.name, t.argument, t.call?.id ?? null, t.result?.id ?? null, t.status]),
    ).toEqual([
      ['Read', 'src/a.ts', a.id, ra.id, 'error'],
      ['Bash', 'git status', b.id, rb.id, 'ok'],
      ['shell', 'ls -la', c.id, rc.id, 'ok'],
      ['shell', 'pwd', d.id, rd.id, 'error'],
      ['Grep', 'TODO', e.id, null, 'pending'],
      ['?', '', null, orphan.id, 'ok'],
    ]);
    expect(turn?.tools).toMatchObject({ calls: 6, ok: 3, error: 2, pending: 1, messages: 0 });
    expect(turn?.tools.byName).toEqual([
      { name: 'shell', count: 2 },
      { name: '?', count: 1 },
      { name: 'Bash', count: 1 },
      { name: 'Grep', count: 1 },
      { name: 'Read', count: 1 },
    ]);
    expect(turn?.reply?.id).toBe(last.id);
  });

  it('keep the agent’s messages on the way in the work, and its last one as the reply', () => {
    const p = user('Refactor it.');
    const m1 = reply('Let me look first.');
    const c1 = call('Read', '{"file_path":"x.ts"}', { callId: '1' });
    const r1 = result('...', { callId: '1' });
    const m2 = reply('Now the edit.');
    const c2 = call('Edit', '{"file_path":"x.ts"}', { callId: '2' });
    const r2 = result('ok', { callId: '2' });
    const done = reply('Done: **x.ts** is pure now.');
    const trail = user('<command-name>/clear</command-name>');
    const [turn] = groupTurns([p, m1, c1, r1, m2, c2, r2, done, trail], [{ id: p.id }], 1);
    expect(kinds(turn?.work ?? [])).toEqual(['message', 'tool', 'message', 'tool']);
    expect(turn?.reply?.id).toBe(done.id);
    expect(kinds(turn?.trail ?? [])).toEqual(['note']);
    expect(turn?.tools.messages).toBe(2);
    // A turn that ends with a call has no reply: everything is work.
    const q = user('Run it.');
    const [open] = groupTurns([q, reply('Running.'), call('Bash', 'x')], [{ id: q.id }], 1);
    expect(open?.reply).toBeNull();
    expect(kinds(open?.work ?? [])).toEqual(['message', 'tool']);
  });

  it('mark the steps of sub-agents, and never take their messages as the reply', () => {
    const p = user('Survey the tests.');
    const task = call('Task', '{"description":"Survey","prompt":"List tests"}', { toolUseId: 't' });
    const subPrompt = user('List tests', { meta: { sidechain: true } });
    const subCall = call('Glob', '{"pattern":"test/**"}', { toolUseId: 'g', sidechain: true });
    const subResult = result('a.test.ts', { toolUseId: 'g', sidechain: true });
    const subReply = reply('One test.', { meta: { sidechain: true } });
    const taskResult = result('One test.', { toolUseId: 't' });
    const [turn] = groupTurns(
      [p, task, subPrompt, subCall, subResult, subReply, taskResult],
      [{ id: p.id }],
      1,
    );
    expect(turn?.reply).toBeNull();
    expect(turn?.work.map((i) => [i.type, i.subAgent])).toEqual([
      ['tool', false],
      ['message', true],
      ['tool', true],
      ['message', true],
    ]);
    expect(turn?.tools).toMatchObject({ calls: 2, ok: 2, messages: 1 });
  });

  it('last from their first event to their last', () => {
    const p = user('Go.', { ts: 1_000 });
    const r = reply('Done.', { ts: 61_500 });
    const [turn] = groupTurns([p, r], [{ id: p.id }], 1);
    expect([turn?.startedAt, turn?.endedAt]).toEqual([1_000, 61_500]);
  });
});

describe('tool arguments', () => {
  it('take the key argument of a JSON input, relative to the working directory', () => {
    expect(
      toolArgument('{"file_path":"/home/dev/demo/src/a.ts","limit":20}', '/home/dev/demo'),
    ).toBe('src/a.ts');
    expect(toolArgument('{"file_path":"D:\\\\dev\\\\demo\\\\src\\\\a.ts"}', 'D:\\dev\\demo')).toBe(
      'src\\a.ts',
    );
    expect(toolArgument('{"pattern":"TODO","path":"src"}')).toBe('TODO');
    expect(toolArgument('{"path":"src"}')).toBe('src');
    expect(toolArgument('{"url":"https://example.com","prompt":"x"}')).toBe('https://example.com');
    expect(toolArgument('{"query":"sqlite iterate"}')).toBe('sqlite iterate');
    expect(toolArgument('{"command":["bash","-lc","rg timeout src"],"workdir":"/x"}')).toBe(
      'rg timeout src',
    );
    expect(toolArgument('{"command":"git status\\n  && git log"}')).toBe('git status && git log');
    expect(toolArgument('{"description":"Survey","prompt":"List"}')).toBe('Survey');
    expect(toolArgument('{"other":"value"}')).toBe('value');
    expect(toolArgument('{"n":1,"m":[2]}')).toBe('{"n":1,"m":[2]}');
  });

  it('read an input cut short, a patch, or plain text', () => {
    expect(toolArgument('{"command":"npm test -- --watch=false","descr…[+512 chars]')).toBe(
      'npm test -- --watch=false',
    );
    expect(toolArgument('{"old_string":"a","file_path":"src/b.ts","new_str…[+9 chars]')).toBe(
      'src/b.ts',
    );
    expect(
      toolArgument(
        '*** Begin Patch\n*** Update File: /w/src/a.ts\n-a\n+b\n*** Add File: /w/src/c.ts\n+c\n*** End Patch',
        '/w',
      ),
    ).toBe('src/a.ts +1');
    expect(toolArgument('ls -la\nmore')).toBe('ls -la');
    expect(toolArgument('')).toBe('');
    expect(toolArgument(`{"command":"${'x'.repeat(400)}"}`)).toHaveLength(160);
  });

  it('take the outcome from the result', () => {
    const r = (meta: Record<string, unknown> | null) => result('x', meta);
    expect(resultStatus(null)).toBe('pending');
    expect(resultStatus(r(null))).toBe('ok');
    expect(resultStatus(r({ isError: true }))).toBe('error');
    expect(resultStatus(r({ status: 'completed' }))).toBe('ok');
    expect(resultStatus(r({ status: 'error' }))).toBe('error');
    expect(resultStatus(r({ status: 'cancelled' }))).toBe('error');
    expect(resultStatus(r({ status: 'in_progress' }))).toBe('pending');
  });
});

describe('notes', () => {
  it('name injected context by its element, and keep its text', () => {
    const note = noteOf(
      ev({
        role: 'user',
        kind: 'meta',
        text: '<system-reminder>\nThe user opened a.ts.\n</system-reminder>',
      }),
    );
    expect(note).toEqual({
      kind: 'context',
      label: 'system-reminder: The user opened a.ts.',
      detail: '<system-reminder>\nThe user opened a.ts.\n</system-reminder>',
    });
    expect(
      noteOf(ev({ role: 'user', kind: 'meta', text: 'Base directory for this skill: /x\n\nMore' })),
    ).toEqual({
      kind: 'context',
      label: 'Base directory for this skill: /x',
      detail: 'Base directory for this skill: /x\n\nMore',
    });
    expect(noteOf(ev({ role: 'system', kind: 'system', text: 'Compacted.' }))).toEqual({
      kind: 'system',
      label: 'Compacted.',
      detail: null,
    });
  });
});

describe('the day index', () => {
  it('gives each day its first turn and how many start on it', () => {
    const day = (d: number, h: number) => new Date(2026, 9, d, h).getTime();
    const prompts = [day(20, 9), day(20, 23), day(21, 1), day(23, 8), day(23, 9), day(23, 10)].map(
      (ts) => ({ ts }),
    );
    expect(dayIndex(prompts)).toEqual([
      { day: '2026-10-20', turn: 1, turns: 2 },
      { day: '2026-10-21', turn: 3, turns: 1 },
      { day: '2026-10-23', turn: 4, turns: 3 },
    ]);
    expect(dayKey(day(5, 0))).toBe('2026-10-05');
    expect(dayIndex([])).toEqual([]);
  });
});

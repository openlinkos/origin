import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import {
  type Database,
  forget,
  getSession,
  listSessions,
  openDatabase,
  PROMPT_TITLE_MAX,
  promptTitle,
  stats,
  syncSource,
} from '../src/index.js';
import { fakeAdapter, line } from './helpers.js';

describe('promptTitle', () => {
  it('keeps what the user typed, on one line', () => {
    expect(promptTitle('  Fix the login\n\n  form, please ')).toBe('Fix the login form, please');
    expect(promptTitle('<div> is not closed, so this is a prompt')).toBe(
      '<div> is not closed, so this is a prompt',
    );
    expect(promptTitle('[Image #1] what is wrong here?')).toBe('[Image #1] what is wrong here?');
  });

  it('skips the context and command echoes agents add, and lone notices', () => {
    // Claude Code: a slash command, its output, and the caveat before them.
    expect(
      promptTitle(
        '<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>',
      ),
    ).toBeNull();
    expect(promptTitle('<local-command-stdout>(no content)</local-command-stdout>')).toBeNull();
    expect(
      promptTitle(
        '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>',
      ),
    ).toBeNull();
    // Codex: the injected environment.
    expect(
      promptTitle('<environment_context>\n  <cwd>/home/dev/app</cwd>\n</environment_context>'),
    ).toBeNull();
    expect(promptTitle('[Request interrupted by user for tool use]')).toBeNull();
    expect(promptTitle(' \n ')).toBeNull();
  });

  it('takes the prompt after the context an agent put before it', () => {
    expect(
      promptTitle(
        '<ide_opened_file>The user opened src/login.ts in the IDE.</ide_opened_file>\nwhy does this throw?',
      ),
    ).toBe('why does this throw?');
    expect(promptTitle('<system-reminder a="1">x</system-reminder><br/> and then this')).toBe(
      'and then this',
    );
  });

  it('cuts a long prompt, by characters', () => {
    const long = promptTitle(`${'部署'.repeat(60)} and more`)!;
    expect([...long]).toHaveLength(PROMPT_TITLE_MAX);
    expect(long.endsWith('…')).toBe(true);
    expect(long.startsWith('部署部署')).toBe(true);
    const emoji = promptTitle('😀'.repeat(100))!;
    expect([...emoji]).toHaveLength(PROMPT_TITLE_MAX);
    expect(emoji.slice(0, -1)).toBe('😀'.repeat(PROMPT_TITLE_MAX - 1));
    // A very long message is read only as far as it needs.
    expect(promptTitle(`[${'x'.repeat(5000)}]`)?.length).toBe(PROMPT_TITLE_MAX);
  });
});

describe('sessions without a title', () => {
  let home: string;
  let src: string;
  let db: Database;
  beforeEach(() => {
    home = fs.mkdtempSync(path.join(os.tmpdir(), 'origin-home-'));
    src = fs.mkdtempSync(path.join(os.tmpdir(), 'origin-src-'));
    db = openDatabase(path.join(home, 'origin.db'));
  });
  afterEach(() => {
    db.close();
    fs.rmSync(home, { recursive: true, force: true });
    fs.rmSync(src, { recursive: true, force: true });
  });

  it('are named by their first prompt, apart from their title, until a title arrives', async () => {
    fs.writeFileSync(
      path.join(src, 'a.jsonl'),
      line('c', 'a', 1000, 'user', '<local-command-caveat>Caveat</local-command-caveat>', 'meta') +
        line('d', 'a', 1001, 'user', '<command-name>/model</command-name>') +
        line('e', 'a', 1002, 'user', '<local-command-stdout>Set model</local-command-stdout>') +
        line('f', 'a', 1003, 'user', 'tool output', 'tool_result') +
        line('g', 'a', 1004, 'assistant', 'Hello! What should we work on?') +
        line('h', 'a', 1005, 'user', 'Rename the billing module') +
        line('i', 'a', 1006, 'user', 'and update its tests'),
    );
    fs.writeFileSync(
      path.join(src, 'b.jsonl'),
      line('j', 'b', 2000, 'assistant', 'Nobody asked me anything.'),
    );
    const adapter = fakeAdapter(src);
    await syncSource({ db, home }, adapter);
    const byId = () => Object.fromEntries(listSessions(db).map((s) => [s.sessionId, s]));
    expect(byId().a).toMatchObject({ title: null, prompt: 'Rename the billing module' });
    expect(byId().b).toMatchObject({ title: null, prompt: null });
    expect(getSession(db, 'fake', 'a')).toMatchObject({ prompt: 'Rename the billing module' });
    expect(stats(db)).toMatchObject([{ source: 'fake', sessions: 2, titled: 0 }]);

    // The prompt is never shown once its event is forgotten (invariant 2): the next one is.
    forget(db, 'fake:h', { reason: 'test' });
    expect(byId().a).toMatchObject({ prompt: 'and update its tests' });

    // Once the session has a title, that is its name, and the prompt is not looked up.
    fs.appendFileSync(
      path.join(src, 'a.jsonl'),
      `${JSON.stringify({ session: 'a', title: 'Billing' })}\n`,
    );
    await syncSource({ db, home }, adapter);
    expect(byId().a).toMatchObject({ title: 'Billing', prompt: null });
    expect(stats(db)).toMatchObject([{ titled: 1 }]);
  });

  it('are looked up through the index of user messages, in time order', () => {
    const plan = db
      .prepare(
        `EXPLAIN QUERY PLAN SELECT e.text FROM event e
          WHERE e.source = ? AND e.session_id = ? AND e.role = 'user' AND e.kind = 'message'
          ORDER BY e.ts, e.seq`,
      )
      .all('fake', 'a') as Array<{ detail: string }>;
    const details = plan.map((p) => p.detail).join('\n');
    expect(details).toContain('event_user_message');
    expect(details).not.toContain('TEMP B-TREE');
  });
});
